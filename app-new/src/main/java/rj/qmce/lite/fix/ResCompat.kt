    fun getString(context: android.content.Context, resId: Int): String = getString(context.resources, resId)

    @JvmStatic
    fun getString(context: android.content.Context, resId: Int, formatArgs: Array<Any>): String =
        getString(context.resources, resId, formatArgs)

    @JvmStatic
    fun getText(context: android.content.Context, resId: Int): CharSequence = getText(context.resources, resId)

    // ── Fragment 版（Fragment 不是 Context，需走 requireContext）──

    @JvmStatic
    fun getString(fragment: androidx.fragment.app.Fragment, resId: Int): String =
        getString(fragment.requireContext(), resId)

    @JvmStatic
    fun getString(fragment: androidx.fragment.app.Fragment, resId: Int, formatArgs: Array<Any>): String =
        getString(fragment.requireContext(), resId, formatArgs)

    // ── Resources 版 ──

    @JvmStatic
    fun getString(resources: Resources, resId: Int): String {
        try {
            return resources.getString(resId)
        } catch (_: Resources.NotFoundException) {
            return QQ_STRINGS[resId] ?: ""
        }
    }

    @JvmStatic
    fun getString(resources: Resources, resId: Int, formatArgs: Array<Any>): String {
        try {
            return resources.getString(resId, *formatArgs)
        } catch (_: Resources.NotFoundException) {
            val fmt = QQ_STRINGS[resId] ?: ""
            return if (formatArgs.isEmpty()) fmt else String.format(fmt, *formatArgs)
        }
    }

    @JvmStatic
    fun getText(resources: Resources, resId: Int): CharSequence {
        try {
            return resources.getText(resId)
        } catch (_: Resources.NotFoundException) {
            return QQ_STRINGS[resId] ?: ""
        }
    }

